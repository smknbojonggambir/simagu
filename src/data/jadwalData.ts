export const getRuangForJadwal = (kelas: string, mapel: string = '', jamKe: string = ''): string => {
  if (roomMap[kelas]) return roomMap[kelas];
  if (kelas.includes('Seluruh Kelas') || kelas.includes('Seluruh')) {
    const m = (mapel || '').toLowerCase();
    const j = (jamKe || '').toLowerCase();
    if (m.includes('shalat') || m.includes('duha') || m.includes('dzuhur') || m.includes('jumat')) return 'Masjid Sekolah';
    if (m.includes('upacara') || m.includes('senam')) return 'Lapangan Utama';
    if (m.includes('baca buku')) return 'Perpustakaan / Kelas';
    if (m.includes('mbg') || j.includes('istirahat 1')) return 'Ruang Kelas Masing-Masing';
    return 'Area Sekolah';
  }
  return 'Ruang Kelas';
};

